#!/usr/bin/env python3
"""Generate the embedded FTEQCC manual and man page from one document."""
import argparse
import json
import re
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
def outputs():
    source = (ROOT / "documentation/FTEQCC.md").read_text()
    plain = "\n".join(line.lstrip("# ") if line.startswith("#") else line for line in source.splitlines()) + "\n"
    header = "/* Generated by tools/build_qcc_manual.py; edit documentation/FTEQCC.md. */\nstatic const char qcc_manual[] =\n"
    header += "".join(json.dumps(line + "\n", ensure_ascii=True) + "\n" for line in plain.splitlines()) + ";\n"
    man = '.TH FTEQCC 1 "October 11, 2026" "FTEQW-SDL3" "User Commands"\n'
    literal = False
    for line in source.splitlines():
        iscode = line.startswith('    ')
        if literal and not iscode:
            man += '.fi\n'
            literal = False
        if line.startswith('# '):
            man += '.SH NAME\nfteqcc \\- QuakeC compiler\n'
        elif line.startswith('## '):
            man += '.SH "' + line[3:].upper() + '"\n'
        elif not line:
            man += '.PP\n'
        else:
            if iscode and not literal:
                man += '.nf\n'
                literal = True
            if not iscode:
                line = '\n'.join(textwrap.wrap(line, width=72, break_long_words=False, break_on_hyphens=False))
            line = line.replace('\\', '\\e').replace('-', '\\-')
            if line.startswith(('.', "'")):
                line = '\\&' + line
            man += line + '\n'
    if literal:
        man += '.fi\n'
    man = re.sub(r'\n\.PP\n(?=\.SH|$)', '\n', man)
    man = re.sub(r'(\.SH[^\n]*\n)\.PP\n', r'\1', man)
    return {ROOT / "engine/qclib/qcc_manual.h": header, ROOT / "documentation/fteqcc.1": man}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files without writing")
    args = parser.parse_args()
    for path, value in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit(f"stale generated manual: {path}")
        elif not path.exists() or path.read_text() != value:
            path.write_text(value)
    print("FTEQCC manual artifacts are current")
if __name__ == "__main__":
    main()
