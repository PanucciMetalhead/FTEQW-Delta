#!/usr/bin/env python3
"""Compile Vulkan shaders, validate them, and embed both Vulkan and Metal sources.

Requires glslangValidator and spirv-val in PATH. The generated header is checked
in, so building the engine needs only SDL3 and a C compiler.
"""
import pathlib
import subprocess
import tempfile

root = pathlib.Path(__file__).resolve().parents[1]
shaderdir = root / 'engine/sdlgpu/shaders'
output = ['/* Generated by tools/build_gpu_shaders.py. Do not edit. */\n']
for program in ('scene', 'post', 'shadow'):
    for stage in ('vert', 'frag'):
        name = f'{program}.{stage}'
        symbol = f'gpu_{program}_{stage}'
        with tempfile.TemporaryDirectory() as tmp:
            spv = pathlib.Path(tmp) / 'shader.spv'
            subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.0', '-o', str(spv), str(shaderdir/name)], check=True)
            subprocess.run(['spirv-val', str(spv)], check=True)
            binary = spv.read_bytes()
        for kind, data in [('spv', binary), ('msl', (shaderdir/(name+'.metal')).read_bytes()+b'\0')]:
            output.append(f'_Alignas(4) static const unsigned char {symbol}_{kind}[] = {{\n')
            for start in range(0, len(data), 20):
                output.append('    '+','.join(str(b) for b in data[start:start+20])+',\n')
            output.append('};\n')
(root/'engine/sdlgpu/gpu_shaders.h').write_text(''.join(output))
